# MAGIC %md
# MAGIC ## 4 · Transform
# MAGIC | Silver column | Rule | Original kept? |
# MAGIC |---|---|---|
# MAGIC | text columns (12) | collapse whitespace runs → one space, trim, blank → `NULL` (defensive; changes nothing in current data) | Bronze |
# MAGIC | `date_received`, `date_sent_to_company` | strict `yyyy-MM-dd` → `DATE`; anything else → `NULL` and fails validation | Bronze |
# MAGIC | `days_to_company` | `datediff(date_sent_to_company, date_received)` | — (derived) |
# MAGIC | `is_timely` | `Yes` → true, `No` → false, else `NULL` (fails validation) | `timely` |
# MAGIC | `state_code` | full name → USPS code (`UM`); codes unchanged | `state` |
# MAGIC | `state_category` | state / district / territory / military / unknown, by USPS list | `state` |
# MAGIC | `tags_list`, `is_servicemember`, `is_older_american` | split `tags` on `", "`; empty array when null | `tags` |
# MAGIC | `sample_*`, `stratum_population`, `source_system` | renamed from Bronze `_stratum`, `_sample_*`, `_source_system` | Bronze |
# MAGIC | `issue`, `company`, `zip_code`, … | unchanged (note: "…existing problem" and "…existing issue" are kept as separate CFPB values) | — |

