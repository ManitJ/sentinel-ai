# MAGIC %md
# MAGIC ## 6 · Parity with the Python reference
# MAGIC Recomputes the profile that `silver_rules.profile()` produced locally from the same Bronze data.
# MAGIC Any difference means the Spark rules and the tested Python rules disagree → the run fails
# MAGIC before anything is written.

# COMMAND ----------

p = silver_df.agg(
    F.count(F.lit(1)).alias("rows"),
    F.sum(F.col("is_timely").cast("int")).alias("is_timely_true"),
    F.sum(F.col("is_servicemember").cast("int")).alias("is_servicemember_true"),
    F.sum(F.col("is_older_american").cast("int")).alias("is_older_american_true"),
    F.sum(F.when(F.size("tags_list") > 0, 1).otherwise(0)).alias("tags_list_nonempty"),
    F.sum(F.when(F.col("state_code") == "UM", 1).otherwise(0)).alias("state_code_UM"),
    F.sum("days_to_company").alias("days_to_company_sum"),
    F.max("days_to_company").alias("days_to_company_max"),
    F.sum("sample_weight").alias("weight_sum"),
    *[F.sum(F.when(F.col(c).isNull(), 1).otherwise(0)).alias(f"null__{c}") for c in NULLABLE_COLUMNS],
    *[F.countDistinct(c).alias(f"distinct__{c}") for c in EXPECTED_PROFILE["distinct_counts"]],
).first()

actual_profile = {
    "rows": p["rows"],
    "is_timely_true": p["is_timely_true"],
    "is_servicemember_true": p["is_servicemember_true"],
    "is_older_american_true": p["is_older_american_true"],
    "tags_list_nonempty": p["tags_list_nonempty"],
    "state_category": {r["k"]: r["n"] for r in silver_df.groupBy(
        F.coalesce("state_category", F.lit("NULL")).alias("k")).agg(F.count(F.lit(1)).alias("n")).collect()},
    "state_code_UM": p["state_code_UM"],
    "days_to_company_sum": p["days_to_company_sum"],
    "days_to_company_max": p["days_to_company_max"],
    "null_counts": {c: p[f"null__{c}"] for c in NULLABLE_COLUMNS},
    "distinct_counts": {c: p[f"distinct__{c}"] for c in EXPECTED_PROFILE["distinct_counts"]},
    "weight_sum_rounded": round(p["weight_sum"], 2),
}

differences = {
    key: {"expected": EXPECTED_PROFILE[key], "actual": actual_profile[key]}
    for key in EXPECTED_PROFILE
    if (abs(actual_profile[key] - EXPECTED_PROFILE[key]) > 0.01 if key == "weight_sum_rounded"
        else actual_profile[key] != EXPECTED_PROFILE[key])
}
if differences:
    raise AssertionError(f"Spark output differs from the Python reference profile: {differences}")
print("[PASS] Spark transformation matches the Python reference profile on all "
      f"{len(EXPECTED_PROFILE)} metrics")

