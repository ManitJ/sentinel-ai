# MAGIC %md
# MAGIC ## 5 · Validate the transformed data (before writing)
# MAGIC Same checks as `validate()` in the Python reference:
# MAGIC IDs (present, numeric, unique, same count as Bronze), required non-null columns, date range and
# MAGIC stratum consistency, no negative `days_to_company`, `timely` ∈ {Yes, No}, known tags only,
# MAGIC 22 strata × 2,273, one population per stratum summing to 10,500,160, and
# MAGIC `sample_weight = stratum_population / stratum size` with Σ weights = population.

# COMMAND ----------

def check(failures, condition, message):
    print(f"[{'PASS' if condition else 'FAIL'}] {message}")
    if not condition:
        failures.append(message)


failures = []

agg = silver_df.agg(
    F.count(F.lit(1)).alias("rows"),
    F.countDistinct("complaint_id").alias("unique_ids"),
    F.sum(F.when(F.col("complaint_id").isNull() | ~F.col("complaint_id").rlike(ID_PATTERN), 1)
          .otherwise(0)).alias("bad_ids"),
    F.sum(F.when((F.col("date_received") < F.lit(DATE_MIN).cast("date"))
                 | (F.col("date_received") >= F.lit(DATE_MAX).cast("date")), 1).otherwise(0)).alias("out_of_range"),
    F.sum(F.when(F.date_format("date_received", "yyyy-MM") != F.col("sample_stratum"), 1)
          .otherwise(0)).alias("misplaced"),
    F.sum(F.when(F.col("days_to_company") < 0, 1).otherwise(0)).alias("negative_lag"),
    F.sum(F.when(~F.col("timely").isin("Yes", "No"), 1).otherwise(0)).alias("bad_timely"),
    F.sum("sample_weight").alias("weight_sum"),
    *[F.sum(F.when(F.col(c).isNull(), 1).otherwise(0)).alias(f"null__{c}") for c in REQUIRED_NON_NULL],
).first()

unknown_tags = [r["tag"] for r in silver_df.select(F.explode("tags_list").alias("tag"))
                .where(~F.col("tag").isin(KNOWN_TAGS)).distinct().collect()]

strata = silver_df.groupBy("sample_stratum").agg(
    F.count(F.lit(1)).alias("n"),
    F.countDistinct("stratum_population").alias("pop_values"),
    F.max("stratum_population").alias("population"),
).collect()
bad_weights = (
    silver_df.withColumn("n", F.count(F.lit(1)).over(Window.partitionBy("sample_stratum")))
    .where((F.col("sample_weight") <= 0)
           | (F.abs(F.col("sample_weight") - F.col("stratum_population") / F.col("n"))
              > F.lit(WEIGHT_TOLERANCE) * F.col("sample_weight")))
    .count()
)

check(failures, agg["rows"] == EXPECTED_ROWS == bronze_rows,
      f"rows {agg['rows']} == expected {EXPECTED_ROWS} == bronze {bronze_rows}")
check(failures, agg["bad_ids"] == 0, f"null/non-numeric complaint_id = {agg['bad_ids']}")
check(failures, agg["unique_ids"] == agg["rows"], f"unique complaint_id {agg['unique_ids']} == rows")
for c in REQUIRED_NON_NULL:
    check(failures, agg[f"null__{c}"] == 0, f"{c} nulls = {agg[f'null__{c}']}")
check(failures, agg["out_of_range"] == 0, f"date_received outside [{DATE_MIN}, {DATE_MAX}) = {agg['out_of_range']}")
check(failures, agg["misplaced"] == 0, f"date_received month != sample_stratum = {agg['misplaced']}")
check(failures, agg["negative_lag"] == 0, f"date_sent_to_company before date_received = {agg['negative_lag']}")
check(failures, agg["bad_timely"] == 0, f"timely outside {{Yes, No}} = {agg['bad_timely']}")
check(failures, not unknown_tags, f"unknown tags = {unknown_tags}")
check(failures, len(strata) == EXPECTED_STRATA, f"strata {len(strata)} == {EXPECTED_STRATA}")
check(failures, {r['n'] for r in strata} == {EXPECTED_PER_STRATUM}, f"every stratum has {EXPECTED_PER_STRATUM} rows")
check(failures, all(r["pop_values"] == 1 for r in strata), "one population value per stratum")
check(failures, sum(r["population"] for r in strata) == EXPECTED_POPULATION,
      f"population total {sum(r['population'] for r in strata):,} == {EXPECTED_POPULATION:,}")
check(failures, bad_weights == 0, f"sample_weight != population / stratum size: {bad_weights}")
check(failures, abs(agg["weight_sum"] - EXPECTED_POPULATION) < 1e-6 * EXPECTED_POPULATION,
      f"sum of weights {agg['weight_sum']:,.2f} == {EXPECTED_POPULATION:,}")

unknown_states = [r["state"] for r in silver_df.where(F.col("state_category") == "unknown")
                  .select("state").distinct().collect()]
if unknown_states:
    print(f"[WARN] unrecognised state values (kept as-is): {unknown_states}")

if failures:
    raise AssertionError(f"Silver validation failed ({len(failures)}): {failures}")

