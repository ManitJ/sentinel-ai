"""Silver transformation rules — pure-Python reference implementation.

The Databricks notebook ``databricks/notebooks/02_silver_transform.py``
implements the same rules with Spark expressions. Parity is enforced two ways:

* constants (state lists, tag vocabulary, required columns, bounds) are
  defined in both places and a unit test asserts they are identical;
* the notebook compares its output profile with ``EXPECTED_PROFILE``, which is
  generated by ``profile(transform(...))`` from this module over the same
  Bronze data, so any Spark/Python divergence fails inside Databricks.

Rules deliberately avoid changing meaning: original values are kept next to
every derived column, and nothing is merged, re-labelled or imputed.
"""

import re
from collections import Counter
from datetime import date

# USPS codes (factual reference lists, not project-specific groupings).
US_STATES = [
    "AK", "AL", "AR", "AZ", "CA", "CO", "CT", "DE", "FL", "GA", "HI", "IA", "ID", "IL",
    "IN", "KS", "KY", "LA", "MA", "MD", "ME", "MI", "MN", "MO", "MS", "MT", "NC", "ND",
    "NE", "NH", "NJ", "NM", "NV", "NY", "OH", "OK", "OR", "PA", "RI", "SC", "SD", "TN",
    "TX", "UT", "VA", "VT", "WA", "WI", "WV", "WY",
]
DISTRICT = ["DC"]
TERRITORIES = ["AS", "FM", "GU", "MH", "MP", "PR", "PW", "UM", "VI"]
MILITARY = ["AA", "AE", "AP"]
# Full names observed in the source instead of a code.
STATE_NAME_TO_CODE = {"UNITED STATES MINOR OUTLYING ISLANDS": "UM"}

KNOWN_TAGS = ["Older American", "Servicemember"]
TIMELY_VALUES = {"Yes": True, "No": False}

TEXT_COLUMNS = [
    "product", "sub_product", "issue", "sub_issue", "company", "company_response",
    "company_public_response", "timely", "submitted_via", "state", "zip_code", "tags",
]
REQUIRED_NON_NULL = [
    "complaint_id", "date_received", "date_sent_to_company", "product", "sub_product",
    "issue", "company", "company_response", "timely", "is_timely", "submitted_via",
    "sample_stratum", "stratum_population", "sample_weight", "sample_key",
]
NULLABLE_COLUMNS = ["sub_issue", "company_public_response", "state", "state_code",
                    "state_category", "zip_code", "tags"]

DATE_MIN = "2025-01-01"   # inclusive
DATE_MAX = "2026-11-01"   # exclusive
EXPECTED_ROWS = 50_006
EXPECTED_STRATA = 22
EXPECTED_PER_STRATUM = 2_273
EXPECTED_POPULATION = 10_500_160
WEIGHT_TOLERANCE = 1e-9

# Silver business columns, in table order (lineage columns follow).
SILVER_COLUMNS = [
    ("complaint_id", "string"),
    ("date_received", "date"),
    ("date_sent_to_company", "date"),
    ("days_to_company", "int"),
    ("product", "string"),
    ("sub_product", "string"),
    ("issue", "string"),
    ("sub_issue", "string"),
    ("company", "string"),
    ("company_response", "string"),
    ("company_public_response", "string"),
    ("timely", "string"),
    ("is_timely", "boolean"),
    ("submitted_via", "string"),
    ("state", "string"),
    ("state_code", "string"),
    ("state_category", "string"),
    ("zip_code", "string"),
    ("tags", "string"),
    ("tags_list", "array<string>"),
    ("is_servicemember", "boolean"),
    ("is_older_american", "boolean"),
    ("sample_stratum", "string"),
    ("stratum_population", "bigint"),
    ("sample_weight", "double"),
    ("sample_key", "string"),
    ("source_system", "string"),
]
LINEAGE_COLUMNS = [
    ("_bronze_record_hash", "string"),
    ("_bronze_loaded_at", "timestamp"),
    ("_bronze_source_file", "string"),
    ("_bronze_table_version", "bigint"),
    ("_silver_record_hash", "string"),
    ("_silver_processed_at", "timestamp"),
]
# Excluded from _silver_record_hash so unchanged rows are not rewritten.
HASH_EXCLUDED = {"_bronze_loaded_at", "_bronze_table_version", "_silver_processed_at",
                 "_silver_record_hash"}

# Regex patterns shared verbatim with the notebook (valid in Python and Java).
# \x0B is used instead of \v, which means different things in the two engines.
WHITESPACE_PATTERN = r"[ \t\n\r\f\x0B]+"
DATE_PATTERN = r"^\d{4}-\d{2}-\d{2}$"
ID_PATTERN = r"^\d+$"
TAG_SPLIT_PATTERN = r", *"

_WHITESPACE = re.compile(WHITESPACE_PATTERN)
_DATE = re.compile(DATE_PATTERN)
_ID = re.compile(ID_PATTERN)
_TAG_SPLIT = re.compile(TAG_SPLIT_PATTERN)


def normalize_text(value):
    """Collapse whitespace runs to one space, trim spaces, blank -> None."""
    if value is None:
        return None
    cleaned = _WHITESPACE.sub(" ", value).strip(" ")
    return cleaned or None


def parse_date(value):
    """Strict YYYY-MM-DD -> date; anything else -> None (flagged by validation)."""
    if value is None or not _DATE.match(value):
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        return None


def state_code(state):
    if state is None:
        return None
    return STATE_NAME_TO_CODE.get(state, state)


def state_category(code):
    if code is None:
        return None
    if code in US_STATES:
        return "state"
    if code in DISTRICT:
        return "district"
    if code in TERRITORIES:
        return "territory"
    if code in MILITARY:
        return "military"
    return "unknown"


def split_tags(tags):
    if tags is None:
        return []
    return [t for t in _TAG_SPLIT.split(tags) if t]


def transform_record(bronze):
    """Map one Bronze row (dict) to a Silver row (dict, business columns)."""
    text = {c: normalize_text(bronze.get(c)) for c in TEXT_COLUMNS}
    received = parse_date(bronze.get("date_received"))
    sent = parse_date(bronze.get("date_sent_to_company"))
    code = state_code(text["state"])
    tags_list = split_tags(text["tags"])
    row = {
        "complaint_id": bronze.get("complaint_id"),
        "date_received": received,
        "date_sent_to_company": sent,
        "days_to_company": (sent - received).days if received and sent else None,
        **{c: text[c] for c in TEXT_COLUMNS},
        "is_timely": TIMELY_VALUES.get(text["timely"]),
        "state_code": code,
        "state_category": state_category(code),
        "tags_list": tags_list,
        "is_servicemember": "Servicemember" in tags_list,
        "is_older_american": "Older American" in tags_list,
        "sample_stratum": bronze.get("_stratum"),
        "stratum_population": bronze.get("_stratum_population"),
        "sample_weight": bronze.get("_sample_weight"),
        "sample_key": bronze.get("_sample_key"),
        "source_system": bronze.get("_source_system"),
    }
    return {name: row[name] for name, _ in SILVER_COLUMNS}  # contract column order


def validate(records):
    """Return (failures, warnings) for a list of Silver rows."""
    failures, warnings = [], []

    def fail(condition, message):
        if not condition:
            failures.append(message)

    ids = [r["complaint_id"] for r in records]
    fail(len(records) == EXPECTED_ROWS, f"rows {len(records)} != {EXPECTED_ROWS}")
    fail(all(i is not None and _ID.match(i) for i in ids), "complaint_id null or non-numeric")
    fail(len(set(ids)) == len(ids), f"duplicate complaint_id: {len(ids) - len(set(ids))}")

    for column in REQUIRED_NON_NULL:
        nulls = sum(1 for r in records if r[column] is None)
        fail(nulls == 0, f"{column} has {nulls} nulls")

    lo, hi = date.fromisoformat(DATE_MIN), date.fromisoformat(DATE_MAX)
    out_of_range = sum(1 for r in records if r["date_received"] and not lo <= r["date_received"] < hi)
    fail(out_of_range == 0, f"date_received outside [{DATE_MIN}, {DATE_MAX}): {out_of_range}")
    misplaced = sum(1 for r in records if r["date_received"]
                    and r["date_received"].strftime("%Y-%m") != r["sample_stratum"])
    fail(misplaced == 0, f"date_received month != sample_stratum: {misplaced}")
    negative = sum(1 for r in records if r["days_to_company"] is not None and r["days_to_company"] < 0)
    fail(negative == 0, f"date_sent_to_company before date_received: {negative}")
    fail(all(r["timely"] in TIMELY_VALUES for r in records), "timely outside {Yes, No}")

    unknown_tags = {t for r in records for t in r["tags_list"]} - set(KNOWN_TAGS)
    fail(not unknown_tags, f"unknown tags: {sorted(unknown_tags)}")

    strata = Counter(r["sample_stratum"] for r in records)
    fail(len(strata) == EXPECTED_STRATA, f"strata {len(strata)} != {EXPECTED_STRATA}")
    fail(set(strata.values()) == {EXPECTED_PER_STRATUM}, "stratum sizes differ from design")
    populations = {}
    for r in records:
        populations.setdefault(r["sample_stratum"], set()).add(r["stratum_population"])
    fail(all(len(v) == 1 for v in populations.values()), "stratum with several population values")
    fail(sum(next(iter(v)) for v in populations.values()) == EXPECTED_POPULATION,
         "population total mismatch")
    bad_weights = sum(
        1 for r in records
        if not r["sample_weight"] or r["sample_weight"] <= 0
        or abs(r["sample_weight"] - r["stratum_population"] / strata[r["sample_stratum"]])
        > WEIGHT_TOLERANCE * r["sample_weight"])
    fail(bad_weights == 0, f"sample_weight != population / stratum size: {bad_weights}")
    weight_sum = sum(r["sample_weight"] or 0 for r in records)
    fail(abs(weight_sum - EXPECTED_POPULATION) < 1e-6 * EXPECTED_POPULATION,
         f"sum of weights {weight_sum:.2f} != {EXPECTED_POPULATION}")

    unknown_states = sorted({r["state"] for r in records if r["state_category"] == "unknown"})
    if unknown_states:
        warnings.append(f"unrecognised state values: {unknown_states}")
    return failures, warnings


def profile(records):
    """Summary the notebook recomputes in Spark; must match exactly."""
    def count(predicate):
        return sum(1 for r in records if predicate(r))

    return {
        "rows": len(records),
        "is_timely_true": count(lambda r: r["is_timely"] is True),
        "is_servicemember_true": count(lambda r: r["is_servicemember"]),
        "is_older_american_true": count(lambda r: r["is_older_american"]),
        "tags_list_nonempty": count(lambda r: len(r["tags_list"]) > 0),
        "state_category": dict(sorted(Counter(
            r["state_category"] or "NULL" for r in records).items())),
        "state_code_UM": count(lambda r: r["state_code"] == "UM"),
        "days_to_company_sum": sum(r["days_to_company"] for r in records),
        "days_to_company_max": max(r["days_to_company"] for r in records),
        "null_counts": {c: count(lambda r, c=c: r[c] is None) for c in NULLABLE_COLUMNS},
        "distinct_counts": {c: len({r[c] for r in records if r[c] is not None})
                            for c in ["issue", "sub_issue", "company", "company_response",
                                      "company_public_response", "submitted_via",
                                      "state_code"]},
        "weight_sum_rounded": round(sum(r["sample_weight"] for r in records), 2),
    }
